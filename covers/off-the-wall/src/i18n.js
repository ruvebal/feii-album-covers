export const LANGS = ['es', 'en'];

/** Idioma guardado o el del navegador. */
export function initialLang() {
  try {
    const saved = window.localStorage.getItem('otw-lang');
    if (LANGS.includes(saved)) return saved;
  } catch {
    // Sin localStorage (modo privado): se usa el del navegador.
  }
  return (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function saveLang(lang) {
  try {
    window.localStorage.setItem('otw-lang', lang);
  } catch {
    // Si no se puede guardar, no pasa nada: vale para esta visita.
  }
}

